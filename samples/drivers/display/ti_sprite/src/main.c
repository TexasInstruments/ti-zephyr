/*
 * TI DSS sprite animation sample — callback-driven
 *
 * Renders a TI logo sprite that slides in small pixel steps in a serpentine
 * (boustrophedon) pattern across the full display window: each row is swept
 * in the opposite direction of the row before it.  The animation loop uses
 * the callback approach implemented in display_tidss.c:
 *
 *   1. display_write() is non-blocking: it enqueues the buffer into the
 *      driver's request queue and returns immediately.
 *   2. At each VSYNC the driver ISR (tidss_isr) dequeues the next buffer,
 *      latches it into the DSS shadow registers, and fires the registered
 *      vsync_cb from ISR context.
 *   3. vsync_cb gives a semaphore that the main thread is blocked on.
 *   4. Once unblocked, the main thread advances the sprite position, renders
 *      the next frame, and calls display_write() again.
 *
 * The display refresh rate is the sole pacing mechanism; no k_msleep() is
 * used anywhere in the animation loop.
 */

#define LOG_LEVEL CONFIG_LOG_DEFAULT_LEVEL
#include <zephyr/logging/log.h>
LOG_MODULE_REGISTER(tidss_sprite);

#include <zephyr/kernel.h>
#include <zephyr/device.h>
#include <zephyr/drivers/display.h>
