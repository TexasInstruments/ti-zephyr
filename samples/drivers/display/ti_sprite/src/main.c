static void sprite_init(void)
{
	for (int y = 0; y < SPRITE_H; y++) {
		for (int x = 0; x < SPRITE_W; x++) {
			bool is_red = ti_logo_bitmap[y][x / 8] & BIT(7 - (x % 8));

			g_sprite[y * SPRITE_W + x] = is_red ? COLOR_RED : COLOR_BG;
		}
	}
}

/*
 * Copy g_sprite into the framebuffer at origin (ox, oy).
 * Pixels that fall outside [0, fw) x [0, fh) are silently clipped.
 */
static void sprite_blit(uint32_t *fb, uint16_t fw, uint16_t fh, int ox, int oy)
{
	for (int sy = 0; sy < SPRITE_H; sy++) {
		int fy = oy + sy;

		if (fy < 0 || fy >= fh) {
			continue;
		}
		for (int sx = 0; sx < SPRITE_W; sx++) {
			int fx = ox + sx;

			if (fx < 0 || fx >= fw) {
				continue;
			}
			fb[(size_t)fy * fw + fx] = g_sprite[sy * SPRITE_W + sx];
		}
	}
}

int main(void)
{
	const struct device *disp = DEVICE_DT_GET(DT_CHOSEN(zephyr_display));
	struct display_capabilities caps;
	struct display_buffer_descriptor desc;
	uint32_t *fb[2];
	uint32_t cb_handle;
	int buf_idx = 0;
	int sprite_x = 0;
	int sprite_y = 0;
	int dir_x = 1;
	int y_target = 0;
	bool descending = false;
	int ret;

	if (!device_is_ready(disp)) {
		LOG_ERR("display not ready");
		return -ENODEV;
	}

	display_get_capabilities(disp, &caps);

	if (caps.current_pixel_format != PIXEL_FORMAT_ARGB_8888) {
		LOG_ERR("sample requires PIXEL_FORMAT_ARGB_8888, got %d",
			caps.current_pixel_format);
		return -ENOTSUP;
	}

	const size_t fb_bytes = (size_t)caps.x_resolution *
				caps.y_resolution * sizeof(uint32_t);
	const size_t fb_npix  = (size_t)caps.x_resolution * caps.y_resolution;

	/*
	 * Two buffers: while the DSS is scanning one, the CPU renders into the
	 * other.  64-byte alignment covers the Cortex-A53 cache line and any
	 * DSS DMA alignment requirement.
	 */
	fb[0] = k_aligned_alloc(64, fb_bytes);
	fb[1] = k_aligned_alloc(64, fb_bytes);
	if (!fb[0] || !fb[1]) {
		LOG_ERR("framebuffer alloc (%zu B x2) failed — increase "
			"CONFIG_HEAP_MEM_POOL_ADD_SIZE_SAMPLE", fb_bytes);
		ret = -ENOMEM;
		goto out_free;
	}

	sprite_init();

	desc.buf_size         = fb_bytes;
	desc.pitch            = caps.x_resolution;
	desc.width            = caps.x_resolution;
	desc.height           = caps.y_resolution;
	desc.frame_incomplete = false;

	ret = display_blanking_off(disp);
	if (ret < 0 && ret != -ENOSYS) {
		LOG_ERR("blanking_off failed: %d", ret);
		goto out_free;
	}
	ret = 0;

	/*
	 * Register vsync_cb for DISPLAY_EVENT_VSYNC, to be called from ISR
	 * context (in_isr = true).  tidss_isr() fires this callback after
	 * latching each new buffer into the DSS shadow registers.
	 */
	ret = display_register_event_cb(disp, vsync_cb, NULL,
					DISPLAY_EVENT_VSYNC, true, &cb_handle);
	if (ret < 0) {
		LOG_ERR("display_register_event_cb failed: %d", ret);
		goto out_free;
	}

	LOG_INF("%s %ux%u ARGB8888 — %ux%u sprite stride-sweep",
		disp->name, caps.x_resolution, caps.y_resolution,
		SPRITE_W, SPRITE_H);

	/* Render the first frame into fb[0] before entering the display loop. */
	for (size_t i = 0; i < fb_npix; i++) {
		fb[0][i] = COLOR_BG;
	}
	sprite_blit(fb[0], caps.x_resolution, caps.y_resolution, sprite_x, sprite_y);

	uint32_t fps_count     = 0;
	int64_t  fps_timestamp = k_uptime_get();

	for (;;) {
		/*
		 * Kick off the non-blocking display write for the current
		 * render buffer.  tidss_write() enqueues fb[buf_idx] into
		 * req_q and returns immediately.  The driver ISR dequeues it
		 * at the next VSYNC, latches it into the DSS shadow registers,
		 * and fires vsync_cb.
		 */
		ret = display_write(disp, 0, 0, &desc, fb[buf_idx]);
		if (ret < 0) {
			LOG_ERR("display_write failed: %d", ret);
			break;
		}

		/*
		 * Block until vsync_cb fires from ISR context and gives this
		 * semaphore.  fb[buf_idx] is now the active DSS scanout buffer
		 * and must not be written until the next swap.
		 */
		k_sem_take(&vsync_sem, K_FOREVER);

		/* FPS: count confirmed VSYNC callbacks; report once per second. */
		fps_count++;
		int64_t now     = k_uptime_get();
		int64_t elapsed = now - fps_timestamp;

		if (elapsed >= 1000) {
			LOG_INF("FPS: %u", (uint32_t)(fps_count * 1000U / elapsed));
			fps_count     = 0;
			fps_timestamp = now;
		}

		/*
		 * Swap to the other buffer.  fb[buf_idx ^ 1] was the previous
		 * scanout and is no longer being read by the hardware, so it
		 * is safe to render into it.
		 */
		buf_idx ^= 1;

		/*
		 * Advance the sprite position and render the next frame.
		 * Each row is swept in the opposite direction of the row
		 * before it (boustrophedon).  Once an edge is reached, the
		 * sprite descends to the next row in STEP_PX increments
		 * rather than jumping the full SPRITE_H in one frame, then
		 * resumes the horizontal sweep in the reversed direction.
		 */
		if (descending) {
			sprite_y += STEP_PX;
			if (sprite_y >= y_target) {
				sprite_y = y_target;
				descending = false;
			}
		} else {
			sprite_x += dir_x * STEP_PX;
			if (dir_x > 0 && sprite_x + SPRITE_W > caps.x_resolution) {
				sprite_x = caps.x_resolution - SPRITE_W;
				dir_x = -1;
				y_target = sprite_y + SPRITE_H;
				if (y_target >= caps.y_resolution) {
					sprite_y = 0;
				} else {
					descending = true;
				}
			} else if (dir_x < 0 && sprite_x < 0) {
				sprite_x = 0;
				dir_x = 1;
				y_target = sprite_y + SPRITE_H;
				if (y_target >= caps.y_resolution) {
					sprite_y = 0;
				} else {
					descending = true;
				}
			}
		}

		for (size_t i = 0; i < fb_npix; i++) {
			fb[buf_idx][i] = COLOR_BG;
		}
		sprite_blit(fb[buf_idx], caps.x_resolution, caps.y_resolution,
			    sprite_x, sprite_y);
	}

	display_unregister_event_cb(disp, cb_handle);

out_free:
	k_free(fb[0]);
	k_free(fb[1]);
	return ret;
}
